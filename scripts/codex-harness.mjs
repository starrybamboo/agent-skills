import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const markerPrefix = '<!-- Generated by pstack Codex harness from ';
const legacyMarkerPrefix = '<!-- Generated by pstack Codex adapter from ';
const adapterVersion = '1';
const encode = value => `${JSON.stringify(value, null, 2)}\n`;
const json = async file => JSON.parse(await fs.readFile(file, 'utf8'));

export async function source(base = root) {
  const lock = await json(path.join(base, 'upstreams.lock.json'));
  const pin = lock.sources?.find(item => item.name === 'pstack');
  if (!pin) throw new Error('upstreams.lock.json has no pstack source');
  const plugin = await json(path.join(base, 'plugins/pstack/.claude-plugin/plugin.json'));
  if (plugin.name !== 'pstack' || !plugin.version) throw new Error('Invalid vendored pstack manifest');
  if (pin.version !== plugin.version) throw new Error('pstack version differs between lock and plugin');
  return { base, version: plugin.version, revision: pin.revision, pluginDir: path.join(base, 'plugins/pstack') };
}

export async function skills(base = root) {
  const sourceInfo = await source(base);
  const directory = path.join(sourceInfo.pluginDir, 'skills');
  const entries = [];
  for (const entry of (await fs.readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    if (!entry.isDirectory()) continue;
    const file = path.join(directory, entry.name, 'SKILL.md');
    const text = await fs.readFile(file, 'utf8');
    const front = text.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
    if (!front) throw new Error(`Missing pstack frontmatter: ${entry.name}`);
    const fields = parse(front[1]);
    if (fields.name !== entry.name || typeof fields.description !== 'string' || !fields.description.trim()) {
      throw new Error(`Invalid pstack skill: ${entry.name}`);
    }
    entries.push({
      name: fields.name,
      description: fields.description.trim(),
      human: fields['disable-model-invocation'] === true,
      directory: entry.name,
    });
  }
  if (!entries.length) throw new Error('pstack has no skills');
  return { source: sourceInfo, entries };
}

function wrapper(sourceInfo, entry) {
  const marker = `${markerPrefix}plugins/pstack at ${sourceInfo.version}, revision ${sourceInfo.revision}. -->`;
  const enter = entry.name === 'poteto-mode' ? '' :
    '\nDo not auto-enter `poteto-mode` unless the user also asks for it or the upstream skill requires it.\n';
  const description = `${entry.description} Explicitly invoke this pstack entry as $${entry.name}.`;
  return `---
name: ${entry.name}
description: ${JSON.stringify(description)}
metadata:
  short-description: ${JSON.stringify(`pstack ${entry.name}`)}
---

${marker}

# pstack ${entry.name}

This is an explicit-only Codex entry for the human-invocable upstream pstack
Skill \`${entry.name}\`.

1. Read \`../pstack/references/codex-adapter.md\` relative to this file once if
   the upstream Skill invokes a subagent, another Skill, or a Claude/Cursor-only
   feature.
2. Run \`../pstack/scripts/resolve-pstack.sh\` relative to this file to resolve
   the installed pstack source.
3. Read \`<pstack-root>/skills/${entry.name}/SKILL.md\` in full and follow it as
   the active workflow.
4. Apply the Codex mapping from the adapter. Do not claim skipped Claude or
   Cursor steps ran.
${enter}`;
}

async function writeFile(file, content) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content);
}

export async function generate(base = root, output = path.join(base, 'harness/codex')) {
  const discovered = await skills(base);
  if (discovered.entries.some(entry => entry.name === 'pstack')) throw new Error('pstack source contains a conflicting pstack skill');
  await fs.rm(path.join(output, 'skills'), { recursive: true, force: true });
  await fs.cp(path.join(base, 'harness/codex/adapter'), path.join(output, 'skills/pstack'), { recursive: true });

  const generated = ['pstack'];
  for (const entry of discovered.entries.filter(item => item.human)) {
    const directory = path.join(output, 'skills', entry.name);
    await writeFile(path.join(directory, 'SKILL.md'), wrapper(discovered.source, entry));
    await writeFile(path.join(directory, 'agents/openai.yaml'), 'policy:\n  allow_implicit_invocation: false\n');
    generated.push(entry.name);
  }

  const state = {
    schemaVersion: 1,
    managedBy: 'pstack-codex-harness',
    adapterVersion,
    source: {
      name: 'pstack',
      version: discovered.source.version,
      revision: discovered.source.revision,
      directory: 'plugins/pstack',
    },
    skills: generated.sort((a, b) => a.localeCompare(b, 'en')),
  };
  await writeFile(path.join(output, 'state.json'), encode(state));
  return state;
}

async function inventory(directory) {
  const files = {};
  async function walk(current, prefix = '') {
    for (const entry of (await fs.readdir(current, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
      const name = prefix + entry.name;
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) await walk(full, `${name}/`);
      else if (entry.isFile()) {
        files[name] = {
          sha256: createHash('sha256').update(await fs.readFile(full)).digest('hex'),
          executable: Boolean((await fs.stat(full)).mode & 0o111),
        };
      } else throw new Error(`Unsupported generated file: ${name}`);
    }
  }
  await walk(directory);
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b, 'en')));
}

export async function check(base = root) {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'pstack-codex-check-'));
  try {
    await generate(base, temporary);
    const generated = path.join(base, 'harness/codex');
    const actual = await inventory(path.join(generated, 'skills'));
    const expected = await inventory(path.join(temporary, 'skills'));
    if (encode(actual) !== encode(expected)) throw new Error('Stale generated Codex skills; run npm run codex:sync');
    if (await fs.readFile(path.join(generated, 'state.json'), 'utf8') !== await fs.readFile(path.join(temporary, 'state.json'), 'utf8')) {
      throw new Error('Stale Codex harness state; run npm run codex:sync');
    }
    return json(path.join(generated, 'state.json'));
  } finally {
    await fs.rm(temporary, { recursive: true, force: true });
  }
}

async function preflightInstall(base, targetSkills, codexHome) {
  const generated = path.join(base, 'harness/codex/skills');
  const names = (await fs.readdir(generated, { withFileTypes: true })).filter(entry => entry.isDirectory()).map(entry => entry.name);
  for (const name of names) {
    const destination = path.join(targetSkills, name);
    if (!(await fs.stat(destination).catch(() => null))) continue;
    const file = path.join(destination, 'SKILL.md');
    const text = await fs.readFile(file, 'utf8').catch(() => '');
    if (!text.includes(markerPrefix) && !text.includes(legacyMarkerPrefix) && !text.includes('Generated by pstack Codex harness')) {
      throw new Error(`Refusing to overwrite non-harness skill: ${destination}`);
    }
  }
  const payload = path.join(codexHome, 'pstack-codex');
  const stateFile = path.join(payload, 'install.json');
  if (await fs.stat(path.join(payload, 'upstream')).catch(() => null)) {
    const prior = await json(stateFile).catch(() => null);
    if (prior?.managedBy !== 'pstack-codex-harness') {
      throw new Error(`Refusing to overwrite unmanaged pstack payload: ${path.join(payload, 'upstream')}`);
    }
  }
  return { names, payload, stateFile };
}

export async function install(base = root, options = {}) {
  const state = await check(base);
  const codexHome = path.resolve(options.codexHome || process.env.CODEX_HOME || path.join(os.homedir(), '.codex'));
  const targetSkills = path.resolve(options.skills || path.join(codexHome, 'skills'));
  const plan = await preflightInstall(base, targetSkills, codexHome);
  await fs.mkdir(targetSkills, { recursive: true });

  const staging = await fs.mkdtemp(path.join(os.tmpdir(), 'pstack-codex-install-'));
  try {
    await fs.cp(path.join(base, 'plugins/pstack'), path.join(staging, 'upstream'), { recursive: true });
    await fs.cp(path.join(base, 'harness/codex/skills'), path.join(staging, 'skills'), { recursive: true });
    await fs.mkdir(plan.payload, { recursive: true });
    const upstream = path.join(plan.payload, 'upstream');
    const upstreamNext = path.join(plan.payload, 'upstream.next');
    await fs.rm(upstreamNext, { recursive: true, force: true });
    await fs.rename(path.join(staging, 'upstream'), upstreamNext);
    await fs.rm(upstream, { recursive: true, force: true });
    await fs.rename(upstreamNext, upstream);

    const previous = await json(plan.stateFile).catch(() => null);
    for (const name of plan.names) {
      const source = path.join(staging, 'skills', name);
      const destination = path.join(targetSkills, name);
      await fs.rm(destination, { recursive: true, force: true });
      await fs.rename(source, destination);
    }
    for (const name of previous?.skills || []) {
      if (plan.names.includes(name)) continue;
      const destination = path.join(targetSkills, name);
      const text = await fs.readFile(path.join(destination, 'SKILL.md'), 'utf8').catch(() => '');
      if (text.includes(markerPrefix) || text.includes(legacyMarkerPrefix)) await fs.rm(destination, { recursive: true, force: true });
    }
    const installState = {
      schemaVersion: 1,
      managedBy: 'pstack-codex-harness',
      installedAt: new Date().toISOString(),
      source: state.source,
      skills: plan.names.sort((a, b) => a.localeCompare(b, 'en')),
      upstream,
    };
    await writeFile(plan.stateFile, encode(installState));
    return installState;
  } finally {
    await fs.rm(staging, { recursive: true, force: true });
  }
}

export async function status(base = root, options = {}) {
  const state = await check(base);
  const codexHome = path.resolve(options.codexHome || process.env.CODEX_HOME || path.join(os.homedir(), '.codex'));
  const installFile = path.join(codexHome, 'pstack-codex/install.json');
  const installed = await json(installFile).catch(() => null);
  if (!installed) return { installed: false, expected: state };
  const drift = [];
  if (installed.source?.version !== state.source.version) drift.push('version');
  if (installed.source?.revision !== state.source.revision) drift.push('revision');
  if (encode(installed.skills) !== encode(state.skills)) drift.push('skills');
  return { installed: true, drift, expected: state, actual: installed };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [command, ...args] = process.argv.slice(2);
  if (command === 'sync' && args.length === 0) {
    const output = path.join(root, 'harness/codex');
    const state = await generate(root, output);
    console.log(`Generated ${state.skills.length} Codex skills from pstack ${state.source.version}.`);
  } else if (command === 'check' && args.length === 0) {
    const state = await check(root);
    console.log(`Verified ${state.skills.length} generated Codex skills.`);
  } else if (command === 'install' && args.every(arg => arg.startsWith('--codex-home=') || arg.startsWith('--skills='))) {
    const options = {};
    for (const arg of args) {
      const [key, ...rest] = arg.slice(2).split('=');
      options[key === 'codex-home' ? 'codexHome' : 'skills'] = rest.join('=');
    }
    const result = await install(root, options);
    console.log(`Installed ${result.skills.length} Codex skills to ${path.dirname(result.upstream)}.`);
  } else if (command === 'status' && args.every(arg => arg.startsWith('--codex-home='))) {
    const options = {};
    for (const arg of args) options.codexHome = arg.slice('--codex-home='.length);
    const result = await status(root, options);
    if (!result.installed) console.log('Codex harness is not installed.');
    else if (result.drift.length) console.log(`Codex harness drift: ${result.drift.join(', ')}.`);
    else console.log(`Codex harness is current at pstack ${result.actual.source.version}.`);
    if (!result.installed || result.drift.length) process.exitCode = 1;
  } else throw new Error('Usage: codex-harness.mjs sync | check | install [--codex-home=PATH] [--skills=PATH] | status [--codex-home=PATH]');
}

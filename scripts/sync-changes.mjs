import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const syncPaths = ['plugins', 'harness/codex', 'upstreams.lock.json', 'skills-manifest.json', 'skills-router.json'];
const revision = /^[a-f0-9]{40}$/;
const ignoredRevision = '0'.repeat(40);
const encode = value => `${JSON.stringify(value, null, 2)}\n`;
const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], { stdio: ['ignore', 'pipe', 'pipe'] });
const isRevisionMetadata = file => ['upstreams.lock.json', 'skills-manifest.json', 'harness/codex/state.json'].includes(file);
const isWrapper = file => /^harness\/codex\/skills\/[^/]+\/SKILL\.md$/.test(file);

function tree(cwd, ref) {
  const bytes = git(cwd, 'ls-tree', '-r', '-z', '--full-tree', ref, '--', ...syncPaths);
  const entries = bytes.toString('utf8');
  if (!Buffer.from(entries).equals(bytes)) throw new Error('Unsupported non-UTF-8 sync path');
  return new Map(entries
    .split('\0').filter(Boolean).map(entry => {
      const [header, ...name] = entry.split('\t');
      const [mode, type, oid] = header.split(' ');
      return [name.join('\t'), { mode, type, oid }];
    }));
}

function withoutRevision(file, bytes) {
  const text = bytes.toString('utf8');
  // Preserve binary data and all non-generated files byte for byte.
  if (!Buffer.from(text).equals(bytes)) return bytes;
  if (isRevisionMetadata(file)) {
    let value;
    try { value = JSON.parse(text); } catch { return bytes; }
    // Only normalize the canonical JSON our generators write, never arbitrary JSON fields.
    if (encode(value) !== text) return bytes;
    const sources = file === 'harness/codex/state.json' ? [value.source] : value.sources;
    if (!Array.isArray(sources)) return bytes;
    for (const source of sources) {
      if (source && typeof source.revision === 'string' && revision.test(source.revision)) source.revision = ignoredRevision;
    }
    return Buffer.from(encode(value));
  }
  if (isWrapper(file)) {
    // Only the generated marker directly after frontmatter. Keep its version and every body byte.
    const frontmatter = text.match(/^---\n[\s\S]*?\n---\n/)?.[0];
    if (!frontmatter) return bytes;
    return Buffer.from(frontmatter + text.slice(frontmatter.length).replace(
      /^(\n<!-- Generated by pstack Codex harness from plugins\/pstack at [^\r\n]+, revision )[a-f0-9]{40}(\. -->\n)/,
      `$1${ignoredRevision}$2`,
    ));
  }
  return bytes;
}

export function hasSyncChanges(cwd, base, candidate) {
  const before = tree(cwd, base);
  const after = tree(cwd, candidate);
  for (const file of new Set([...before.keys(), ...after.keys()])) {
    const old = before.get(file);
    const current = after.get(file);
    if (!old || !current || old.mode !== current.mode || old.type !== current.type) return true;
    if (old.oid === current.oid) continue;
    if (old.type !== 'blob' || !['100644', '100755'].includes(old.mode)) return true;
    if (!isRevisionMetadata(file) && !isWrapper(file)) return true;
    if (!withoutRevision(file, git(cwd, 'cat-file', 'blob', old.oid))
      .equals(withoutRevision(file, git(cwd, 'cat-file', 'blob', current.oid)))) return true;
  }
  return false;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [base, candidate, ...extra] = process.argv.slice(2);
  if (!base || !candidate || extra.length) throw new Error('Usage: sync-changes.mjs BASE CANDIDATE');
  console.log(hasSyncChanges(process.cwd(), base, candidate));
}

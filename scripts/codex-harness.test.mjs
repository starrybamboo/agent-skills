import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { check, generate, install, skills, status } from './codex-harness.mjs';

async function write(file, text) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, text);
}

async function fixture() {
  const base = await fs.mkdtemp(path.join(os.tmpdir(), 'pstack-codex-fixture-'));
  const plugin = path.join(base, 'plugins/pstack');
  await write(path.join(plugin, '.claude-plugin/plugin.json'), JSON.stringify({
    name: 'pstack',
    version: '1.2.3',
    license: 'MIT',
  }));
  await write(path.join(base, 'upstreams.lock.json'), JSON.stringify({
    schemaVersion: 1,
    sources: [{ name: 'pstack', version: '1.2.3', revision: 'a'.repeat(40) }],
  }));
  await write(path.join(plugin, 'skills/bro/SKILL.md'), `---
name: bro
description: Restate the last message plainly.
disable-model-invocation: true
---

Restate it.
`);
  await write(path.join(plugin, 'skills/how/SKILL.md'), `---
name: how
description: Explain how a subsystem works.
disable-model-invocation: true
---

Explain it.
`);
  await write(path.join(plugin, 'skills/setup-pstack/SKILL.md'), `---
name: setup-pstack
description: Configure host models.
---

Configure.
`);
  await write(path.join(base, 'harness/codex/adapter/SKILL.md'), `---
name: pstack
description: Run pstack.
---

<!-- Generated by pstack Codex harness. Source: plugins/pstack. -->

Run \`scripts/resolve-pstack.sh\`.
`);
  await write(path.join(base, 'harness/codex/adapter/references/codex-adapter.md'), '# adapter\n');
  await write(path.join(base, 'harness/codex/adapter/scripts/resolve-pstack.sh'), '#!/bin/sh\n');
  await fs.chmod(path.join(base, 'harness/codex/adapter/scripts/resolve-pstack.sh'), 0o755);
  return base;
}

test('generates the router and only human-invocable pstack entries', async t => {
  const base = await fixture();
  t.after(() => fs.rm(base, { recursive: true, force: true }));
  const discovered = await skills(base);
  assert.deepEqual(discovered.entries.map(entry => [entry.name, entry.human]), [
    ['bro', true],
    ['how', true],
    ['setup-pstack', false],
  ]);
  const state = await generate(base);
  assert.deepEqual(state.skills, ['bro', 'how', 'pstack']);
  assert.equal(state.source.version, '1.2.3');
  assert.match(await fs.readFile(path.join(base, 'harness/codex/skills/bro/agents/openai.yaml'), 'utf8'), /allow_implicit_invocation: false/);
  await assert.rejects(fs.access(path.join(base, 'harness/codex/skills/setup-pstack')), { code: 'ENOENT' });
});

test('check detects a stale generated Skill', async t => {
  const base = await fixture();
  t.after(() => fs.rm(base, { recursive: true, force: true }));
  await generate(base);
  await check(base);
  await fs.appendFile(path.join(base, 'harness/codex/skills/bro/SKILL.md'), '\nlocal edit\n');
  await assert.rejects(check(base), /Stale generated Codex skills/);
});

test('install copies the payload and refuses to overwrite a normal Skill', async t => {
  const base = await fixture();
  const codexHome = await fs.mkdtemp(path.join(os.tmpdir(), 'pstack-codex-home-'));
  t.after(() => Promise.all([fs.rm(base, { recursive: true, force: true }), fs.rm(codexHome, { recursive: true, force: true })]));
  await generate(base);
  const installed = await install(base, { codexHome });
  assert.equal(installed.managedBy, 'pstack-codex-harness');
  assert.equal((await status(base, { codexHome })).drift.length, 0);
  await fs.access(path.join(codexHome, 'pstack-codex/upstream/skills/bro/SKILL.md'));
  await fs.access(path.join(codexHome, 'skills/bro/SKILL.md'));

  const other = await fixture();
  const otherHome = await fs.mkdtemp(path.join(os.tmpdir(), 'pstack-codex-home-'));
  t.after(() => Promise.all([fs.rm(other, { recursive: true, force: true }), fs.rm(otherHome, { recursive: true, force: true })]));
  await generate(other);
  await write(path.join(otherHome, 'skills/bro/SKILL.md'), `---
name: bro
description: User-owned.
---
`);
  await assert.rejects(install(other, { codexHome: otherHome }), /Refusing to overwrite non-harness skill/);
});

test('reinstall removes a previously generated wrapper that left upstream', async t => {
  const base = await fixture();
  const codexHome = await fs.mkdtemp(path.join(os.tmpdir(), 'pstack-codex-home-'));
  t.after(() => Promise.all([fs.rm(base, { recursive: true, force: true }), fs.rm(codexHome, { recursive: true, force: true })]));
  await generate(base);
  await install(base, { codexHome });
  await fs.rm(path.join(base, 'plugins/pstack/skills/bro'), { recursive: true });
  await generate(base);
  await install(base, { codexHome });
  await assert.rejects(fs.access(path.join(codexHome, 'skills/bro')), { code: 'ENOENT' });
});

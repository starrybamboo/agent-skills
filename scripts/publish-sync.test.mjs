const substantiveCases = {
  'skill body': repo => write(repo, 'plugins/example', 'changed skill'),
  'binary resource': repo => write(repo, 'plugins/asset.bin', Buffer.from([0, 255, 128])),
  'resource addition': repo => write(repo, 'plugins/extra.txt', 'added'),
  'resource deletion': repo => fs.rm(path.join(repo, 'plugins/example')),
  'executable mode': repo => fs.chmod(path.join(repo, 'plugins/example'), 0o755),
  'generated file mode': repo => fs.chmod(path.join(repo, 'harness/codex/skills/example/SKILL.md'), 0o755),
  'generated body': repo => fs.appendFile(path.join(repo, 'harness/codex/skills/example/SKILL.md'), 'Real behavior change\n'),
  'generated annotation version': repo => write(repo, 'harness/codex/skills/example/SKILL.md', wrapper('b'.repeat(40)).replace(' at 1,', ' at 2,')),
  'plugin version': repo => write(repo, 'plugins/plugin.json', encode({ version: '2' })),
  'lock version': async repo => {
    const data = JSON.parse(await fs.readFile(path.join(repo, 'upstreams.lock.json'), 'utf8'));
    data.sources[0].version = '2';
    await write(repo, 'upstreams.lock.json', encode(data));
  },
  'nested revision field': async repo => {
    const data = JSON.parse(await fs.readFile(path.join(repo, 'skills-manifest.json'), 'utf8'));
    data.sources[0].adapter = { revision: 'b'.repeat(40) };
    await write(repo, 'skills-manifest.json', encode(data));
  },
  'JSON formatting': async repo => {
    const file = 'upstreams.lock.json';
    await write(repo, file, JSON.stringify(JSON.parse(await fs.readFile(path.join(repo, file), 'utf8'))));
  },
  'invalid source revision': repo => setRevision(repo, 'not-a-commit'),
  'malformed generated JSON': repo => write(repo, 'upstreams.lock.json', '{'),
};

for (const [name, change] of Object.entries(substantiveCases)) {
  test(`${name} is substantive despite revision churn`, async t => {
    const f = await fixture(t);
    await setRevision(f.repo, 'b'.repeat(40));
    await change(f.repo);
    git(f.repo, 'add', '.');
    assert.equal(hasSyncChanges(f.repo, 'origin/main', git(f.repo, 'write-tree')), true);
  });
}

test('marker-like revision changes in imported content or later wrapper body are not suppressed', async t => {
  for (const file of ['plugins/example', 'harness/codex/skills/example/SKILL.md']) {
    const f = await fixture(t);
    const before = `---\nname: example\n---\n\n# User content\n---\n\n${marker('a'.repeat(40))}\n`;
    await write(f.repo, file, before);
    git(f.repo, 'add', '.'); git(f.repo, 'commit', '-m', 'body marker');
    const base = git(f.repo, 'rev-parse', 'HEAD');
    await write(f.repo, file, before.replace('a'.repeat(40), 'b'.repeat(40)));
    git(f.repo, 'add', '.');
    assert.equal(hasSyncChanges(f.repo, base, git(f.repo, 'write-tree')), true);
  }
});

test('comparison failure stops publication rather than treating it as no changes', async t => {
  const f = await fixture(t);
  git(f.repo, 'update-ref', '-d', 'refs/remotes/origin/main');
  const result = f.run();
  assert.notEqual(result.status, 0);
  assert.equal(git(f.repo, 'rev-parse', 'HEAD'), f.baseline);
  await assert.rejects(fs.access(f.log), { code: 'ENOENT' });
});

test('renames from outside the sync paths cannot bypass either allowlist', async t => {
  for (const committed of [false, true]) {
    const f = await fixture(t);
    git(f.repo, 'mv', 'README.md', 'plugins/README.md');
    if (committed) git(f.repo, 'commit', '-m', 'unrelated rename');
    const result = f.run();
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /Unexpected (staged|sync branch) change: README.md/);
    assert.throws(() => git(f.remote, 'rev-parse', 'sync/pstack'));
    await assert.rejects(fs.access(f.log), { code: 'ENOENT' });
  }
});

test('invalid UTF-8 paths fail closed instead of collapsing distinct file names', async t => {
  const f = await fixture(t);
  const file = Buffer.concat([Buffer.from(path.join(f.repo, 'plugins/')), Buffer.from([255])]);
  await fs.writeFile(file, 'opaque path');
  git(f.repo, 'add', '.');
  assert.throws(() => hasSyncChanges(f.repo, 'origin/main', git(f.repo, 'write-tree')), /non-UTF-8 sync path/);
});
